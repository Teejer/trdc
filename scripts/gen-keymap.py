#!/usr/bin/env python3
"""Generate src-tauri/src/rdp/keymap.rs from guacamole-server's generated
keymaps (Apache-2.0), the same X11-keysym -> RDP-scancode tables xrdp uses.

Run from the trdc repo root (the source table is vendored under
scripts/keymaps/ so regeneration does not need a guacamole-server checkout):

    python3 scripts/gen-keymap.py \
        scripts/keymaps/guacamole-1.6.0-_generated_keymaps.c \
        src-tauri/src/rdp/keymap.rs

"""
import re
import sys

CONSTS = {
    "GUAC_RDP_KEYMAP_MODIFIER_SHIFT": 1,
    "GUAC_RDP_KEYMAP_MODIFIER_ALTGR": 2,
    "KBD_FLAGS_EXTENDED": 0x0100,
    "KBD_FLAGS_EXTENDED1": 0x0200,
    "KBD_SYNC_SCROLL_LOCK": 0x1,
    "KBD_SYNC_NUM_LOCK": 0x2,
    "KBD_SYNC_CAPS_LOCK": 0x4,
    "KBD_SYNC_KANA_LOCK": 0x8,
}

def eval_expr(expr: str) -> int:
    expr = expr.strip()
    for name, val in CONSTS.items():
        expr = expr.replace(name, str(val))
    # only digits, |, &, ^, ~, parens, whitespace, hex allowed
    if not re.fullmatch(r"[0-9a-fA-Fx|\(\)&~\s^+-]+", expr):
        raise ValueError(f"cannot evaluate expression: {expr!r}")
    return int(eval(expr))  # noqa: S307 - input is tightly regex-gated

def main(src: str, dst: str) -> None:
    text = open(src).read()

    # keysym desc arrays: static guac_rdp_keysym_desc __guac_rdp_keymap_NAME[] = {...};
    arrays = {}
    for m in re.finditer(
        r"static guac_rdp_keysym_desc __guac_rdp_keymap_(\w+)\[\] = \{(.*?)\n\};",
        text, re.S):
        name, body = m.group(1), m.group(2)
        entries = []
        for em in re.finditer(r"\{([^}]*)\}", body):
            fields = dict(re.findall(r"\.(\w+) = ([^,}]+(?:\|[^,}]+)*)", em.group(1)))
            if "keysym" not in fields or eval_expr(fields["keysym"]) == 0:
                continue
            entries.append({
                "keysym": eval_expr(fields["keysym"]),
                "scancode": eval_expr(fields.get("scancode", "0")),
                "flags": eval_expr(fields.get("flags", "0")),
                "set_modifiers": eval_expr(fields.get("set_modifiers", "0")),
                "clear_modifiers": eval_expr(fields.get("clear_modifiers", "0")),
                "set_locks": eval_expr(fields.get("set_locks", "0")),
                "clear_locks": eval_expr(fields.get("clear_locks", "0")),
            })
        arrays[name] = entries

    # keymap structs with parent chains
    keymaps = {}
    for m in re.finditer(
        r"static const guac_rdp_keymap guac_rdp_keymap_(\w+) = \{(.*?)\n\};",
        text, re.S):
        name, body = m.group(1), m.group(2)
        km_name = re.search(r'\.name = "([^"]+)"', body).group(1)
        parent = re.search(r"\.parent = &guac_rdp_keymap_(\w+)", body)
        mapping = re.search(r"\.mapping = __guac_rdp_keymap_(\w+)", body)
        keymaps[name] = (km_name, parent.group(1) if parent else None,
                         mapping.group(1) if mapping else None)

    def flatten(name: str) -> list:
        """Parent definitions first, then own (matches guacamole's load order)."""
        _, parent, mapping = keymaps[name]
        defs = flatten(parent) if parent else []
        defs.extend(arrays.get(mapping or "", []))
        return defs

    out = ["""// Generated by scripts/gen-keymap.py from guacamole-server 1.6.0's
// src/protocols/rdp/_generated_keymaps.c (Apache License 2.0). Do not edit.
//
// X11 keysym -> RDP scancode definitions per keyboard layout, including the
// modifier/lock requirements guacamole's keyboard.c uses to pick between
// multiple definitions of the same keysym (see keyboard.rs).

#![allow(clippy::all)]
// Layout-named statics (KEYMAP_en_us_qwerty) intentionally keep the wire
// spelling of the layout names rather than SCREAMING_CASE.
#![allow(non_upper_case_globals)]

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct KeyDef {
    pub keysym: i32,
    pub scancode: u16,
    /// KBD_FLAGS_* (extended etc), sent alongside the scancode.
    pub flags: u16,
    /// GUAC_RDP_KEYMAP_MODIFIER_* that must be pressed for this keysym.
    pub set_modifiers: u32,
    /// GUAC_RDP_KEYMAP_MODIFIER_* that must NOT be pressed for this keysym.
    pub clear_modifiers: u32,
    /// KBD_SYNC_* locks that must be on for this keysym.
    pub set_locks: u32,
    /// KBD_SYNC_* locks that must be off for this keysym.
    pub clear_locks: u32,
}

pub const DEFAULT_LAYOUT: &str = "en-us-qwerty";
"""]
    for name in sorted(keymaps):
        km_name, _, _ = keymaps[name]
        defs = flatten(name)
        if not defs:
            continue
        ident = km_name.replace('-', '_')
        out.append(f'pub static KEYMAP_{ident}: &[KeyDef] = &[')
        for d in defs:
            out.append(
                f"    KeyDef {{ keysym: {d['keysym']}, scancode: {d['scancode']},"
                f" flags: {d['flags']}, set_modifiers: {d['set_modifiers']},"
                f" clear_modifiers: {d['clear_modifiers']}, set_locks: {d['set_locks']},"
                f" clear_locks: {d['clear_locks']} }},")
        out.append("];\n")

    out.append("pub static KEYMAPS: &[(&str, &[KeyDef])] = &[")
    for name in sorted(keymaps):
        km_name, _, _ = keymaps[name]
        if flatten(name):
            out.append(f'    ("{km_name}", KEYMAP_{km_name.replace("-", "_")}),')
    out.append("];\n")

    open(dst, "w").write("\n".join(out))
    total = sum(len(flatten(n)) for n in keymaps)
    print(f"wrote {dst}: {len(keymaps)} layouts, {total} flattened definitions")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
